def seed_demo(today: Optional[date] = None) -> int:
    """Create the demo account if missing (or rebuild it when the sample data has been updated). Returns its user id."""
    today = today or date.today()
    with connect() as conn:
        row = conn.execute("SELECT id FROM users WHERE email = ?", (DEMO_EMAIL,)).fetchone()
        meta = conn.execute("SELECT value FROM app_meta WHERE key = 'demo_version'").fetchone()
    if row and meta and meta["value"] == DEMO_VERSION:
        return row["id"]
    if row:  # older sample data: rebuild it (only the fictional demo account is touched)
        try:
            auth.delete_account(row["id"], DEMO_PASSWORD)
        except auth.AuthError:
            return row["id"]  # someone changed the demo password; leave it alone
    uid = _seed(today)
    with connect() as conn:
        conn.execute("INSERT OR REPLACE INTO app_meta (key, value) VALUES ('demo_version', ?)", (DEMO_VERSION,))
    return uid


