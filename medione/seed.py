def make_png(title: str, lines: list[str]) -> bytes:
    """A simple receipt-style PNG (stands in for a phone photo of a paper document)."""
    import io

    from PIL import Image, ImageDraw
    img = Image.new("RGB", (620, 120 + 26 * len(lines)), "#FFFDF7")
    draw = ImageDraw.Draw(img)
    draw.text((24, 22), title, fill="#111111")
    draw.line((24, 50, 596, 50), fill="#999999")
    for i, line in enumerate(lines):
        draw.text((24, 66 + 26 * i), line, fill="#333333")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


