def make_pdf(title: str, lines: list[str]) -> bytes:
    """A minimal one-page text PDF (Helvetica), enough for realistic sample documents."""
    def esc(s: str) -> str:
        s = s.encode("ascii", "replace").decode("ascii")
        return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")

    body = ["BT", "/F1 15 Tf", "50 790 Td", "18 TL", f"({esc(title)}) Tj", "/F1 10 Tf", "14 TL", "T*"]
    body += [f"({esc(line)}) Tj T*" for line in lines]
    body += ["T*", "(SAMPLE DOCUMENT - fictional data generated by Thought Medione) Tj", "ET"]
    stream = "\n".join(body).encode("latin-1")
    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R "
        b"/Resources << /Font << /F1 5 0 R >> >> >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for i, obj in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + obj + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    out += b"".join(f"{o:010d} 00000 n \n".encode() for o in offsets)
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def _d(days: int, today: date) -> str:
    return (today + timedelta(days=days)).isoformat()


def _lab_pdf(name: str, facility: str, doctor: str, when: str, labs: list[dict]) -> bytes:
    lines = [f"Patient: {name}", f"Collected: {when}", f"Referred by: {doctor}", f"Laboratory: {facility}", "",
             "Test                         Result      Unit        Reference range"]
    for l in labs:
        ref = l.get("ref_text") or f"{l.get('ref_low', '')} - {l.get('ref_high', '')}"
        lines.append(f"{l['test_name']:<29}{l['value_text']:<12}{l.get('unit') or '':<12}{ref}")
    lines += ["", "Values outside the reference range should be discussed with your doctor."]
    return make_pdf(f"{facility} - Laboratory Report", lines)


