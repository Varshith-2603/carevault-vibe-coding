"""File exports: CSV tables, calendar invites and printable HTML summaries."""
import html
from datetime import date, datetime, timedelta, timezone
from typing import Any, Dict, Iterable, List, Tuple

import pandas as pd

from utils.helpers import display, format_date, is_missing, parse_date
from utils.records import RECORD_TYPES, record_subtitle, record_title, vitals_summary

DEMO_NOTE = "CareVault demo export — contains fictional demo data. Verify all medical information with a qualified healthcare professional."


def to_csv(df: pd.DataFrame, columns: Dict[str, str] | None = None) -> bytes:
    """CSV bytes (UTF-8 with BOM so spreadsheet apps detect the encoding). ``columns`` maps source -> header."""
    out = df.drop(columns=[c for c in df.columns if c.startswith("_")], errors="ignore")
    if columns:
        out = out[[c for c in columns if c in out.columns]].rename(columns=columns)
    return out.to_csv(index=False).encode("utf-8-sig")


def appointment_ics(apt: Dict[str, Any]) -> bytes:
    """A standards-compliant single-event calendar file for an appointment."""
    d = parse_date(apt.get("date")) or date.today()
    start = None
    if not is_missing(apt.get("time")):
        for fmt in ("%I:%M %p", "%H:%M"):
            try:
                start = datetime.combine(d, datetime.strptime(str(apt["time"]).strip(), fmt).time())
                break
            except ValueError:
                continue

    def ics_text(value: str) -> str:
        return value.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")

    lines = [
        "BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//CareVault//Personal Health Records//EN", "BEGIN:VEVENT",
        f"UID:{apt.get('apt_id', 'apt')}@carevault.local",
        f"DTSTAMP:{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}",
    ]
    if start:
        lines += [f"DTSTART:{start.strftime('%Y%m%dT%H%M%S')}", f"DTEND:{(start + timedelta(minutes=30)).strftime('%Y%m%dT%H%M%S')}"]
    else:
        lines += [f"DTSTART;VALUE=DATE:{d.strftime('%Y%m%d')}", f"DTEND;VALUE=DATE:{(d + timedelta(days=1)).strftime('%Y%m%d')}"]
    summary = f"{display(apt.get('type'), 'Appointment')} — {display(apt.get('doctor'), '')}".strip(" —")
    location = ", ".join(display(apt.get(k)) for k in ("room", "facility") if not is_missing(apt.get(k)))
    lines += [f"SUMMARY:{ics_text(summary)}"]
    if location:
        lines.append(f"LOCATION:{ics_text(location)}")
    if not is_missing(apt.get("instructions")):
        lines.append(f"DESCRIPTION:{ics_text(str(apt['instructions']))}")
    lines += ["END:VEVENT", "END:VCALENDAR"]
    return ("\r\n".join(lines) + "\r\n").encode("utf-8")


_PRINT_CSS = """
body{font-family:-apple-system,'Segoe UI',Roboto,Arial,sans-serif;color:#172033;margin:32px auto;max-width:820px;padding:0 20px;line-height:1.5}
h1{font-size:22px;margin:0 0 4px} h2{font-size:16px;margin:28px 0 8px;border-bottom:1px solid #E2E8F0;padding-bottom:4px}
.meta{color:#64748B;font-size:13px} .note{background:#FFF7ED;border:1px solid #FED7AA;padding:8px 12px;border-radius:6px;font-size:12px;margin:16px 0}
table{border-collapse:collapse;width:100%;font-size:13px} th,td{border:1px solid #E2E8F0;padding:6px 8px;text-align:left;vertical-align:top}
th{background:#F7F9FC;width:30%} .block{white-space:pre-wrap;border:1px solid #E2E8F0;padding:8px 12px;border-radius:6px;font-size:13px}
@media print{body{margin:0}.note{border-color:#999}}
"""


def _doc(title: str, body: str) -> bytes:
    return (
        f"<!doctype html><html lang='en'><head><meta charset='utf-8'><title>{html.escape(title)}</title>"
        f"<style>{_PRINT_CSS}</style></head><body>{body}"
        f"<p class='meta'>Generated by CareVault on {date.today().strftime('%d %b %Y')}. Open this file in a browser and use Print to save as PDF.</p>"
        f"</body></html>"
    ).encode("utf-8")


def _table(pairs: Iterable[Tuple[str, Any]]) -> str:
    rows = "".join(f"<tr><th>{html.escape(k)}</th><td>{html.escape(display(v))}</td></tr>" for k, v in pairs)
    return f"<table>{rows}</table>"


def printable_record(kind: str, rec: Dict[str, Any], patient: Dict[str, Any]) -> bytes:
    """Printable copy of one record with the fields exactly as recorded."""
    rt = RECORD_TYPES[kind]
    title = f"{rt.label}: {record_title(kind, rec)}"
    body = f"<h1>{html.escape(title)}</h1>"
    body += f"<div class='meta'>Record {html.escape(str(rec.get(rt.id_col, '')))} · {html.escape(format_date(rec.get(rt.date_col)))}</div>"
    body += f"<div class='note'>{html.escape(DEMO_NOTE)}</div>"
    body += "<h2>Patient</h2>" + _table([("Name", patient.get("name")), ("Patient ID", patient.get("patient_id"))])
    for section, fields in rt.sections:
        pairs = []
        for f in fields:
            if f.kind == "visit_link":
                continue
            v = rec.get(f.name)
            if f.kind in ("date", "optional_date"):
                v = format_date(v) if not is_missing(v) else v
            pairs.append((f.label, v))
        body += f"<h2>{html.escape(section)}</h2>" + _table(pairs)
    return _doc(title, body)


def printable_summary(patient: Dict[str, Any], frames: Dict[str, pd.DataFrame], include: List[str]) -> bytes:
    """Printable health summary. ``include`` lists the record kinds to add after the emergency details."""
    body = f"<h1>Health summary — {html.escape(display(patient.get('name')))}</h1>"
    body += f"<div class='meta'>Patient ID {html.escape(display(patient.get('patient_id')))}</div>"
    body += f"<div class='note'>{html.escape(DEMO_NOTE)}</div>"
    body += "<h2>Emergency information</h2>" + _table([
        ("Blood type", display(patient.get("blood_type"), "Not provided")),
        ("Known allergies", display(patient.get("allergies"), "Not provided")),
        ("Medical conditions", display(patient.get("primary_condition"), "Not provided")),
        ("Emergency contact", display(patient.get("emergency_contact"), "Not provided")),
        ("Emergency phone", display(patient.get("emergency_phone"), "Not provided")),
    ])
    for kind in include:
        rt = RECORD_TYPES[kind]
        df = frames.get(kind)
        if df is None:
            continue
        body += f"<h2>{html.escape(rt.plural)} ({len(df)})</h2>"
        if df.empty:
            body += "<p class='meta'>No records.</p>"
            continue
        rows = "".join(
            "<tr>"
            f"<td>{html.escape(format_date(r.get(rt.date_col)))}</td>"
            f"<td>{html.escape(record_title(kind, r))}</td>"
            f"<td>{html.escape(record_subtitle(kind, r) if kind != 'vital' else vitals_summary(r))}</td>"
            f"<td>{html.escape(display(r.get('status'), '—') if kind != 'vital' else '')}</td>"
            "</tr>"
            for r in df.to_dict(orient="records")
        )
        body += f"<table><tr><th style='width:16%'>Date</th><th style='width:30%'>Record</th><th>Details</th><th style='width:14%'>Status</th></tr>{rows}</table>"
    return _doc("CareVault health summary", body)
